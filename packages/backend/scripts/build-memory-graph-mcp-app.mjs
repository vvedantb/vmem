import * as esbuild from "esbuild";
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const pkgRoot = path.join(__dirname, "..");
const uiDir = path.join(pkgRoot, "mcp-ui", "memory-graph");
const outFile = path.join(
  pkgRoot,
  "convex",
  "mcp",
  "bundled",
  "memoryGraphHtml.ts",
);

// cosmos default import from gl-bench: browser field points at umd bundle
const glBenchEsm = path.join(
  path.dirname(require.resolve("gl-bench/package.json")),
  "dist/gl-bench.module.js",
);

const css = fs.readFileSync(path.join(uiDir, "main.css"), "utf8");

const buildResult = await esbuild.build({
  entryPoints: [path.join(uiDir, "main.ts")],
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  target: "es2020",
  minify: true,
  sourcemap: false,
  logLevel: "info",
  alias: {
    "gl-bench": glBenchEsm,
  },
});

const outputFile = buildResult.outputFiles[0];
if (outputFile === undefined) {
  throw new Error("esbuild produced no output");
}
const js = outputFile.text;

const html = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <title>vmem Memory Graph</title>
  <style>${css}</style>
</head>
<body data-theme="dark">
  <div id="root">
    <header id="toolbar">
      <div class="toolbar-left">
        <span class="app-title">Memory graph</span>
        <span id="stats">Waiting for tool result…</span>
      </div>
      <div class="toolbar-right">
        <span id="hint">Drag to pan · Scroll to zoom</span>
      </div>
    </header>
    <div id="canvas-wrap">
      <div id="loading" class="hidden">
        <div class="spinner" aria-hidden="true"></div>
        <span>Loading graph…</span>
      </div>
      <div id="graph-host"></div>
      <canvas id="label-canvas"></canvas>
      <div id="webgl-error" role="alert"></div>
      <div id="nav-controls">
        <button type="button" class="nav-btn" id="btn-zoom-in" title="Zoom in" aria-label="Zoom in">
          <svg viewBox="0 0 24 24"><path d="M12 5v14M5 12h14"/></svg>
        </button>
        <button type="button" class="nav-btn" id="btn-zoom-out" title="Zoom out" aria-label="Zoom out">
          <svg viewBox="0 0 24 24"><path d="M5 12h14"/></svg>
        </button>
        <button type="button" class="nav-btn" id="btn-fit" title="Fit to view" aria-label="Fit to view">
          <svg viewBox="0 0 24 24"><path d="M9 4H4v5M20 4h-5v5M4 15v5h5M20 15v5h-5"/></svg>
        </button>
      </div>
      <aside id="legend" aria-label="Graph legend">
        <p class="legend-title">Legend</p>
        <p id="legend-stats" class="tabular-nums">—</p>
        <div class="legend-row"><span class="swatch swatch-node"></span><span>Colour = first tag</span></div>
        <div class="legend-row"><span class="swatch swatch-relates"></span><span>Relates-to</span></div>
        <div class="legend-row"><span class="swatch swatch-tag"></span><span>Shared tag</span></div>
      </aside>
      <div id="banner" role="status"></div>
    </div>
  </div>
  <script>${js}</script>
</body>
</html>`;

const tsSource = `// Generated by scripts/build-memory-graph-mcp-app.mjs — do not edit by hand.\nexport const MEMORY_GRAPH_MCP_APP_HTML: string = ${JSON.stringify(html)};\n`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, tsSource, "utf8");
console.log(
  `Wrote ${outFile} (${html.length.toLocaleString()} bytes HTML, js ${(js.length / 1024).toFixed(0)} KiB)`,
);
