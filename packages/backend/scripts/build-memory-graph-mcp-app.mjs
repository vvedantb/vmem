import * as esbuild from "esbuild";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const pkgRoot = path.join(__dirname, "..");
const uiDir = path.join(pkgRoot, "mcp-ui", "memory-graph");
const outFile = path.join(pkgRoot, "convex", "mcp", "bundled", "memoryGraphHtml.ts");

const css = fs.readFileSync(path.join(uiDir, "main.css"), "utf8");

const buildResult = await esbuild.build({
  entryPoints: [path.join(uiDir, "main.ts")],
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  target: "es2020",
  minify: true,
  sourcemap: false,
  logLevel: "info",
});

const js = buildResult.outputFiles[0].text;

const html = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <title>vmem Memory Graph</title>
  <style>${css}</style>
</head>
<body data-theme="dark">
  <div id="root">
    <div id="toolbar">
      <span id="stats">Waiting for tool result…</span>
      <span id="hint"></span>
    </div>
    <div id="canvas-wrap">
      <div id="loading">Loading graph…</div>
      <canvas id="graph-canvas"></canvas>
      <div id="banner"></div>
    </div>
  </div>
  <script>${js}</script>
</body>
</html>`;

const tsSource = `// Generated by scripts/build-memory-graph-mcp-app.mjs — do not edit by hand.\nexport const MEMORY_GRAPH_MCP_APP_HTML: string = ${JSON.stringify(html)};\n`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, tsSource, "utf8");
console.log(`Wrote ${outFile} (${html.length} bytes HTML)`);
