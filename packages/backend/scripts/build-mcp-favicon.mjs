import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const pkgRoot = path.join(__dirname, "..");
const faviconPath = path.join(
  pkgRoot,
  "..",
  "..",
  "apps",
  "web",
  "public",
  "favicon.png",
);
const outFile = path.join(pkgRoot, "convex", "mcp", "bundled", "mcpFaviconPng.ts");

const bytes = fs.readFileSync(faviconPath);
const base64 = bytes.toString("base64");

const tsSource = `// Generated by scripts/build-mcp-favicon.mjs — do not edit by hand.
export const MCP_FAVICON_PNG_BASE64: string = ${JSON.stringify(base64)};
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, tsSource, "utf8");
console.log(`Wrote ${outFile} (${bytes.length} bytes PNG)`);
